precision = precision_score(y_test, y_pred_log)

# Recall
recall = recall_score(y_test, y_pred_log)

# F1 Score
f1 = f1_score(y_test, y_pred_log)

# Confusion Matrix
cm = confusion_matrix(y_test, y_pred_log)

print("Model Evaluation Results")
